#!/usr/bin/env python3
"""Assembles finished TikTok videos for RigFloorHQ from the existing frame
images (social/tiktok/*-frameN.png, generated by make-tiktok-frames.ps1) plus
narration and burned captions generated here.

Narration comes from edge-tts (free, local, no API key) rather than TikTok's
own built-in TTS, because upload now goes through Metricool instead of
TikTok's native composer -- so TikTok's own "turn auto-captions on" step
never runs. Captions are burned in here instead, timed to edge-tts's own
word-boundary timestamps rather than a separate speech-to-text pass, since we
already know exactly what's being said (we generated it).

Scripts below are copies of social/README.md's five spoken videos (01-05).
Keep them in sync with the README if either changes. Videos 06-08 are
screen-recording bookends, not narrated slideshows -- record those manually.

Requires: ffmpeg on PATH, `pip install edge-tts`.

Run:
  python scripts/make-tiktok-videos.py            all five videos
  python scripts/make-tiktok-videos.py 01 05       just these ids
"""
